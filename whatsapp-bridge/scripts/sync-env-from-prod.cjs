/**
 * Builds whatsapp-bridge/.env from whatsapp-bridge/.env.example + root .env.prod.
 * Does not commit secrets — run locally only. .env is gitignored.
 *
 *   node scripts/sync-env-from-prod.cjs
 *   node scripts/sync-env-from-prod.cjs /path/to/.env.prod
 */
const fs = require("fs");
const path = require("path");

const bridgeRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(bridgeRoot, "..");
const defaultProd = path.join(repoRoot, ".env.prod");
const examplePath = path.join(bridgeRoot, ".env.example");
const outPath = path.join(bridgeRoot, ".env");

function parseEnvFile(filePath) {
  const raw = fs.readFileSync(filePath, "utf8");
  const map = {};
  for (const line of raw.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq <= 0) continue;
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    map[key] = val;
  }
  return map;
}

function n8nWebhookFromPublic(publicUrl) {
  const base = String(publicUrl || "").trim().replace(/\/+$/, "");
  if (!base) return "http://127.0.0.1:5678/webhook/whatsapp";
  return `${base}/webhook/whatsapp`;
}

function main() {
  const prodPath = path.resolve(process.argv[2] || defaultProd);
  if (!fs.existsSync(prodPath)) {
    console.error(`Missing ${prodPath}\nCopy .env.prod.example to .env.prod and fill secrets first.`);
    process.exit(1);
  }
  if (!fs.existsSync(examplePath)) {
    console.error(`Missing ${examplePath}`);
    process.exit(1);
  }

  const prod = parseEnvFile(prodPath);
  const exampleLines = fs.readFileSync(examplePath, "utf8").split(/\r?\n/);

  const opsPort = prod.OPS_PUBLISH_PORT || "3001";
  const n8nWebhook = n8nWebhookFromPublic(
    prod.N8N_PUBLIC_WEBHOOK_URL || "http://127.0.0.1:5678/",
  );

  const overrides = {
    N8N_WEBHOOK_URL: n8nWebhook,
    N8N_WEBHOOK_HMAC_SECRET: prod.N8N_WEBHOOK_HMAC_SECRET || "",
    OPS_DASHBOARD_URL: `http://127.0.0.1:${opsPort}`,
    SCHEDULING_SERVICE_TOKEN: prod.SCHEDULING_SERVICE_TOKEN || "",
    BRIDGE_SEND_API_TOKEN:
      prod.BRIDGE_SEND_API_TOKEN || prod.BRIDGE_SEND_TOKEN || "",
  };
  if (prod.CLINIC_ID) overrides.CLINIC_ID = prod.CLINIC_ID;
  if (prod.BRIDGE_PORT) overrides.BRIDGE_PORT = prod.BRIDGE_PORT;

  const out = [];
  for (const line of exampleLines) {
    const m = /^([A-Z_][A-Z0-9_]*)=(.*)$/.exec(line);
    if (m && Object.prototype.hasOwnProperty.call(overrides, m[1])) {
      const v = overrides[m[1]];
      out.push(`${m[1]}=${v}`);
      continue;
    }
    out.push(line);
  }

  const banner =
    `# Generated by scripts/sync-env-from-prod.cjs from ${path.basename(prodPath)} — do not commit.\n` +
    `# Generated at ${new Date().toISOString()}\n\n`;

  fs.writeFileSync(outPath, banner + out.join("\n") + "\n", "utf8");
  fs.chmodSync(outPath, 0o600);
  console.log(`Wrote ${outPath}`);
}

main();
